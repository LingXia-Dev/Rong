#!/usr/bin/env python3
"""Generates src/cldr_units.rs: CLDR's unit patterns for ECMA-402's
sanctioned simple units and the compound units CLDR names, in the long,
short and narrow widths, with each width's `{0} per {1}` pattern.

ICU4X's unit name data covers area, duration, length, mass and volume
only; digital, temperature, angle and percent are missing, so every
sanctioned unit comes from this one table.

The CLDR release is cldr_numbers.py's. Only locales that change a lookup
are kept, as there; strings are stored once.

    python3 quickjs/intl/tools/cldr_units.py          # rewrite the table
    python3 quickjs/intl/tools/cldr_units.py --check  # fail if it is stale
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cldr_dates import package, rust  # noqa: E402
from cldr_numbers import CLDR_VERSION, ancestors  # noqa: E402

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "src" / "cldr_units.rs"
# ECMA-402's sanctioned simple units, and the compounds of them CLDR has
# its own names for.
UNITS = sorted("""
acre bit byte celsius centimeter day degree fahrenheit fluid-ounce foot
gallon gigabit gigabyte gram hectare hour inch kilobit kilobyte kilogram
kilometer liter megabit megabyte meter microsecond mile mile-scandinavian
milliliter millimeter millisecond minute month nanosecond ounce percent
petabyte pound second stone terabit terabyte week yard year
kilometer-per-hour meter-per-second mile-per-hour liter-per-kilometer
mile-per-gallon
""".split())
WIDTHS = ("long", "short", "narrow")
COUNTS = ("zero", "one", "two", "few", "many", "other")
NONE = 0xFFFF


def load():
    units = {}
    with package("cldr-units-full") as tar:
        for member in tar.getmembers():
            parts = member.name.split("/")
            if len(parts) == 4 and parts[1] == "main" and parts[3] == "units.json":
                locale = parts[2]
                units[locale] = json.load(tar.extractfile(member))["main"][locale]["units"]
    with package("cldr-core") as tar:
        member = tar.getmember("package/supplemental/parentLocales.json")
        parents = json.load(tar.extractfile(member))["supplemental"]["parentLocales"]["parentLocale"]
    return units, parents


def row(data):
    """A locale's patterns: per width, each unit's (counts..., per), then
    each width's compound pattern."""
    out = []
    for width in WIDTHS:
        table = data[width]
        by_name = {k.split("-", 1)[1]: v for k, v in table.items() if "-" in k and not k[0].isdigit()}
        for unit in UNITS:
            entry = by_name[unit]
            out.append(
                tuple(entry.get(f"unitPattern-count-{c}") for c in COUNTS) + (entry.get("perUnitPattern"),)
            )
    out.extend(data[w]["per"]["compoundUnitPattern"] for w in WIDTHS)
    return tuple(out)


def generate():
    units, parents = load()
    rows = {locale: row(data) for locale, data in units.items()}
    base = rows["und"]
    kept = {}
    for locale in sorted(rows):
        mine = rows[locale]
        above = any(rows.get(a) not in (None, base) for a in ancestors(locale, parents) if a in rows)
        if locale == "und" or mine != base or above:
            kept[locale] = mine

    strings, string_index = [], {}

    def intern(text):
        if text is None:
            return NONE
        if text not in string_index:
            string_index[text] = len(strings)
            strings.append(text)
        return string_index[text]

    entries, entry_index = [], {}

    def entry(patterns):
        key = tuple(intern(p) for p in patterns)
        if key not in entry_index:
            entry_index[key] = len(entries)
            entries.append(key)
        return entry_index[key]

    distinct, distinct_index, locale_rows = [], {}, []
    for locale, data in kept.items():
        if data not in distinct_index:
            per_unit = len(WIDTHS) * len(UNITS)
            encoded = tuple(entry(p) for p in data[:per_unit]) + tuple(intern(p) for p in data[per_unit:])
            distinct_index[data] = len(distinct)
            distinct.append(encoded)
        locale_rows.append((locale, distinct_index[data]))
    assert len(strings) < NONE and len(entries) < NONE

    offsets, at = [], 0
    for text in strings:
        offsets.append(at)
        at += len(text.encode())
    offsets.append(at)

    lines = [
        "// @generated by tools/cldr_units.py from CLDR " + CLDR_VERSION + "; do not edit.",
        "//! CLDR unit patterns for ECMA-402's sanctioned units.",
        "#![cfg_attr(rustfmt, rustfmt::skip)]",
        "",
        "/// The units, sorted; a row holds each width's units in this order.",
        "pub(crate) static UNITS: &[&str] = &[",
        *[f'    "{u}",' for u in UNITS],
        "];",
        "",
        "/// No pattern.",
        f"pub(crate) const NONE: u16 = {NONE};",
        "",
        "/// Every string, end to end; string i runs from OFFSETS[i] to OFFSETS[i + 1].",
        "pub(crate) static TEXT: &str = concat!(",
    ]
    chunk = []
    for text in strings:
        chunk.append(text)
        if sum(len(t) for t in chunk) > 80:
            lines.append("    " + rust("".join(chunk)) + ",")
            chunk = []
    if chunk:
        lines.append("    " + rust("".join(chunk)) + ",")
    lines += [
        ");",
        "",
        "pub(crate) static OFFSETS: &[u32] = &[",
        *["    " + ", ".join(str(o) for o in offsets[i:i + 16]) + "," for i in range(0, len(offsets), 16)],
        "];",
        "",
        "/// A unit's patterns in one width: the zero, one, two, few, many and",
        "/// other counts, then its per-unit pattern; each a string or NONE.",
        "pub(crate) static ENTRIES: &[[u16; 7]] = &[",
        *["    [" + ", ".join(str(i) for i in e) + "]," for e in entries],
        "];",
        "",
        f"/// Per locale: an entry for each width ({', '.join(WIDTHS)}) and unit,",
        "/// then each width's compound pattern string.",
        f"pub(crate) static ROWS: &[[u16; {len(WIDTHS) * len(UNITS) + len(WIDTHS)}]] = &[",
    ]
    for encoded in distinct:
        lines.append("    [" + ", ".join(str(i) for i in encoded) + "],")
    lines += [
        "];",
        "",
        "/// Each locale's row. Sorted.",
        "pub(crate) static LOCALES: &[(&str, u16)] = &[",
        *[f'    ("{k}", {v}),' for k, v in locale_rows],
        "];",
        "",
    ]
    return "\n".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale: run tools/cldr_units.py")
        print(f"{OUT.name} matches CLDR {CLDR_VERSION}")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
