#!/usr/bin/env python3
"""Generates src/cldr_dates.rs: the CLDR date data ICU4X's data does not
carry yet: each region's hour cycles (timeData: the preferred one, and the
first 12-hour one it allows), and the flexible day periods (`B`: "in the
afternoon"), their rules per language and their names per locale.

The CLDR release is cldr_numbers.py's, which checks it against ICU4X's.
Only entries that change a lookup are kept, as there.

    python3 intl/tools/cldr_dates.py          # rewrite the table
    python3 intl/tools/cldr_dates.py --check  # fail if it is stale
"""

import io
import json
import sys
import tarfile
import unicodedata
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cldr_numbers import CLDR_VERSION, ancestors  # noqa: E402

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "src" / "cldr_dates.rs"
# The flexible day periods, in CLDR's order; a language without rules of
# its own (root's) has am and pm.
PERIODS = ("midnight", "noon", "morning1", "morning2", "afternoon1", "afternoon2",
           "evening1", "evening2", "night1", "night2", "am", "pm")
CYCLES = {"H": "h23", "h": "h12", "K": "h11", "k": "h24"}


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "rong-intl-generator"})
    with urllib.request.urlopen(request, timeout=300) as response:
        return response.read()


def package(name):
    url = f"https://registry.npmjs.org/{name}/-/{name}-{CLDR_VERSION}.tgz"
    return tarfile.open(fileobj=io.BytesIO(fetch(url)), mode="r:gz")


def load():
    with package("cldr-core") as tar:
        def supplemental(name):
            return json.load(tar.extractfile(f"package/supplemental/{name}.json"))["supplemental"]
        time_data = supplemental("timeData")["timeData"]
        rules = supplemental("dayPeriods")["dayPeriodRuleSet"]
        parents = supplemental("parentLocales")["parentLocales"]["parentLocale"]
    names = {}
    with package("cldr-dates-full") as tar:
        for member in tar.getmembers():
            parts = member.name.split("/")
            if len(parts) == 4 and parts[1] == "main" and parts[3] == "ca-gregorian.json":
                locale = parts[2]
                data = json.load(tar.extractfile(member))
                periods = data["main"][locale]["dates"]["calendars"]["gregorian"]["dayPeriods"]["format"]
                names[locale] = tuple(
                    (p, periods["narrow"].get(p), periods["abbreviated"].get(p), periods["wide"].get(p))
                    for p in PERIODS
                    if p in periods["wide"]
                )
    return time_data, rules, parents, names


def minutes(text):
    hours, mins = text.split(":")
    return int(hours) * 60 + int(mins)


def rust(text):
    out = ""
    for ch in text:
        if ch in '"\\':
            out += "\\" + ch
        elif unicodedata.category(ch) in ("Cc", "Cf", "Zl", "Zp") or (
            unicodedata.category(ch) == "Zs" and ch != " "
        ):
            out += "\\u{%x}" % ord(ch)
        else:
            out += ch
    return '"' + out + '"'


def generate():
    time_data, rules, parents, names = load()

    cycles = []
    for key, entry in sorted(time_data.items()):
        preferred = CYCLES[entry["_preferred"][0]]
        twelve = next((CYCLES[a[0]] for a in entry["_allowed"].split() if a[0] in "hK"), "h12")
        cycles.append((key.replace("_", "-"), preferred, twelve))

    rule_lines = []
    for language, periods in sorted(rules.items()):
        spans = []
        for period, rule in sorted(periods.items(), key=lambda kv: PERIODS.index(kv[0])):
            if "_at" in rule:
                at = minutes(rule["_at"])
                spans.append((period, at, at))
            else:
                spans.append((period, minutes(rule["_from"]), minutes(rule["_before"])))
        rule_lines.append((language.replace("_", "-"), spans))

    kept = {}
    for locale in sorted(names):
        mine = names[locale]
        base = names.get("und") or names.get("root")
        differs = mine != base
        above = any(names.get(a) not in (None, base) for a in ancestors(locale, parents) if a in names)
        if locale in ("und", "root") or differs or above:
            kept["und" if locale == "root" else locale] = mine
    sets = sorted(set(kept.values()))
    index = {v: i for i, v in enumerate(sets)}

    lines = [
        "// @generated by tools/cldr_dates.py from CLDR " + CLDR_VERSION + "; do not edit.",
        "//! CLDR date data ICU4X's data does not carry yet.",
        "#![cfg_attr(rustfmt, rustfmt::skip)]",
        "",
        "/// timeData by region or locale: the preferred hour cycle and the first",
        "/// 12-hour one allowed. Sorted by key.",
        "pub(crate) static HOUR_CYCLES: &[(&str, &str, &str)] = &[",
        *[f'    ("{k}", "{p}", "{t}"),' for k, p, t in cycles],
        "];",
        "",
        "/// A day period's rule: (period, from, before) in minutes of the day;",
        "/// `from == before` is an `at` rule.",
        "pub(crate) type DayPeriodRule = (&'static str, u16, u16);",
        "",
        "/// A day period's names: (period, narrow, short, long).",
        "pub(crate) type DayPeriodName = (&'static str, &'static str, &'static str, &'static str);",
        "",
        "/// Each language's day period rules. Sorted by language.",
        "pub(crate) static DAY_PERIOD_RULES: &[(&str, &[DayPeriodRule])] = &[",
    ]
    for language, spans in rule_lines:
        body = ", ".join(f'("{p}", {a}, {b})' for p, a, b in spans)
        lines.append(f'    ("{language}", &[{body}]),')
    lines += [
        "];",
        "",
        "/// Day period names in the format context.",
        "pub(crate) static DAY_PERIOD_NAME_SETS: &[&[DayPeriodName]] = &[",
    ]
    for entry in sets:
        body = ", ".join(
            "(" + ", ".join(rust(x or "") for x in row) + ")" for row in entry
        )
        lines.append(f"    &[{body}],")
    lines += [
        "];",
        "",
        "/// Each locale's names, as an index into DAY_PERIOD_NAME_SETS. Sorted.",
        "pub(crate) static DAY_PERIOD_NAMES: &[(&str, u16)] = &[",
        *[f'    ("{k}", {index[v]}),' for k, v in sorted(kept.items())],
        "];",
        "",
    ]
    return "\n".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is stale: run tools/cldr_dates.py")
        print(f"{OUT.name} matches CLDR {CLDR_VERSION}")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
